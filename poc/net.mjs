import { createRequire } from 'node:module';
const require = createRequire('C:/Playground/ssh-persistant/vscodium/vscode/package.json');
const { chromium } = require('playwright-core');
const [, , win, label] = process.argv;
const b = await chromium.connectOverCDP('http://127.0.0.1:9333');
let p; for (const x of b.contexts().flatMap(c => c.pages())) if ((await x.title()).includes(win)) p = x;
const cdp = await p.context().newCDPSession(p);
const out = [];
cdp.on('Network.loadingFailed', e => out.push(`FAILED ${e.requestId} ${e.errorText} ${e.blockedReason ?? ''}`));
const reqs = {};
cdp.on('Network.requestWillBeSent', e => { reqs[e.requestId] = e.request.url; });
cdp.on('Network.responseReceived', e => { if (e.response.status >= 400) out.push(`HTTP ${e.response.status} ${e.response.url}`); });
cdp.on('Log.entryAdded', e => out.push(`LOG ${e.entry.level} ${e.entry.text} ${e.entry.url ?? ''}`));
await cdp.send('Network.enable'); await cdp.send('Log.enable');
await p.bringToFront(); await p.keyboard.press('Escape'); await p.keyboard.press('F1'); await p.waitForTimeout(500);
await p.keyboard.type(label, { delay: 5 }); await p.waitForTimeout(700);
const idx = await p.evaluate(l => [...document.querySelectorAll('.quick-input-widget .monaco-list-row')].findIndex(r => (r.getAttribute('aria-label') || '').startsWith(l + ',')), label);
await p.locator('.quick-input-widget .monaco-list-row').nth(idx).click();
await p.waitForTimeout(5000);
console.log(out.map(l => l.replace(/FAILED (\S+)/, (m, id) => 'FAILED ' + (reqs[id] ?? id))).join('\n') || 'nothing');
process.exit(0);
