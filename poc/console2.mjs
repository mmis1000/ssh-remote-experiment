import { createRequire } from 'node:module';
const require = createRequire('C:/Playground/ssh-persistant/vscodium/vscode/package.json');
const { chromium } = require('playwright-core');
const b = await chromium.connectOverCDP('http://127.0.0.1:9333');
let p; for (const x of b.contexts().flatMap(c => c.pages())) if ((await x.title()).includes(process.argv[2])) p = x;
const cdp = await p.context().newCDPSession(p);
const logs = [];
cdp.on('Runtime.consoleAPICalled', e => logs.push(e.type + ' ' + e.args.map(a => a.value ?? a.description ?? '').join(' ')));
cdp.on('Runtime.exceptionThrown', e => logs.push('EXC ' + (e.exceptionDetails.exception?.description ?? e.exceptionDetails.text)));
await cdp.send('Runtime.enable');
await p.bringToFront();
await p.keyboard.press('Escape');
await p.keyboard.press('F1');
await p.waitForTimeout(500);
await p.keyboard.type('Terminal: Create New Terminal', { delay: 5 });
await p.waitForTimeout(700);
const idx = await p.evaluate(l => [...document.querySelectorAll('.quick-input-widget .monaco-list-row')].findIndex(r => (r.getAttribute('aria-label')||'').startsWith(l + ',')), 'Terminal: Create New Terminal');
await p.locator('.quick-input-widget .monaco-list-row').nth(idx).click();
await p.waitForTimeout(8000);
console.log(logs.filter(l => !/^(debug|log) .*%c (INFO|TRACE|DEBUG)/.test(l)).slice(-30).join('\n---\n'));
process.exit(0);
